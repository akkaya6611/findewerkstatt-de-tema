    /** Eklenti aktive edildiğinde çalışır */
    public static function install() {
        global $wpdb;
        $table   = $wpdb->prefix . self::TABLE;
        $charset = $wpdb->get_charset_collate();

        $sql = "CREATE TABLE IF NOT EXISTS $table (
            id          MEDIUMINT(9) UNSIGNED NOT NULL AUTO_INCREMENT,
            code        VARCHAR(10)  NOT NULL,
            category    CHAR(1)      NOT NULL,
            name_tr     VARCHAR(255) NOT NULL,
            PRIMARY KEY (id),
            UNIQUE KEY code (code),
            KEY category (category)
        ) $charset;";

        require_once ABSPATH . 'wp-admin/includes/upgrade.php';
        dbDelta( $sql );

        if ( get_option( 'ak_db_seeded' ) !== self::VERSION ) {
            self::seed( $table );
            update_option( 'ak_db_seeded', self::VERSION );
        }
    }

    /** Tüm kodları DB'ye yükle */
    private static function seed( $table ) {
        global $wpdb;
        $wpdb->query( "TRUNCATE TABLE $table" );

        $all = self::all_codes();
        $rows = [];
        foreach ( $all as $cat => $codes ) {
            foreach ( $codes as $code => $name ) {
                $rows[] = $wpdb->prepare( '(%s,%s,%s)', $code, $cat, $name );
            }
        }

        // Toplu insert — 500'er chunk
        foreach ( array_chunk( $rows, 500 ) as $chunk ) {
            $wpdb->query(
                "INSERT IGNORE INTO $table (code, category, name_tr) VALUES " . implode( ',', $chunk )
            );
        }
    }

