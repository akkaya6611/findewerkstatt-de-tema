    /** Kategorideki kod sayısı */
    public static function count( $category ) {
        global $wpdb;
        $table = $wpdb->prefix . self::TABLE;
        return (int) $wpdb->get_var( $wpdb->prepare( "SELECT COUNT(*) FROM $table WHERE category=%s", $category ) );
    }

    /** Sayfalı liste */
    public static function get_page( $category, $page = 1, $per_page = 50, $search = '' ) {
        global $wpdb;
        $table  = $wpdb->prefix . self::TABLE;
        $offset = ( $page - 1 ) * $per_page;

        if ( $search ) {
            return $wpdb->get_results( $wpdb->prepare(
                "SELECT code, name_tr FROM $table WHERE category=%s AND (code LIKE %s OR name_tr LIKE %s) ORDER BY code LIMIT %d OFFSET %d",
                $category, "%$search%", "%$search%", $per_page, $offset
            ), ARRAY_A );
        }

        return $wpdb->get_results( $wpdb->prepare(
            "SELECT code, name_tr FROM $table WHERE category=%s ORDER BY code LIMIT %d OFFSET %d",
            $category, $per_page, $offset
        ), ARRAY_A );
    }

    /** Arama (tüm kategoriler) */
    public static function search( $q, $limit = 100 ) {
        global $wpdb;
        $table = $wpdb->prefix . self::TABLE;
        return $wpdb->get_results( $wpdb->prepare(
            "SELECT code, category, name_tr FROM $table WHERE code LIKE %s OR name_tr LIKE %s ORDER BY code LIMIT %d",
            "%$q%", "%$q%", $limit
        ), ARRAY_A );
    }

    /** Tek kod */
    public static function get_code( $code ) {
        global $wpdb;
        $table = $wpdb->prefix . self::TABLE;
        return $wpdb->get_row( $wpdb->prepare(
            "SELECT * FROM $table WHERE code=%s", $code
        ), ARRAY_A );
    }

    /** Kategori için tüm kodlar (blog için) */
    public static function get_all_by_category( $category ) {
        global $wpdb;
        $table = $wpdb->prefix . self::TABLE;
        $rows  = $wpdb->get_results( $wpdb->prepare(
            "SELECT code, name_tr FROM $table WHERE category=%s ORDER BY code",
            $category
        ), ARRAY_A );
        $result = [];
        foreach ( $rows as $r ) $result[ $r['code'] ] = $r['name_tr'];
        return $result;
    }

